// MIG-323 S6: the console's Content-Security-Policy, written for nginx from the build itself.
//
//   node scripts/csp.mjs <dist/next/browser/index.html> <enforce|report> > csp.conf
//
// index.html keeps two inline scripts (the theme taken before Angular boots, and the critical-CSS loader the build adds);
// each is allowed by its own sha256, so a policy can never drift from the build it ships with. Everything else the
// console runs comes from its own origin. The output is an nginx include for the server block: it sets $csp (the policy
// without frame-ancestors, which each location adds), $csp_enforced and $csp_report, one of them empty (nginx sends no
// header whose value is empty).
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

const [file, mode = 'enforce'] = process.argv.slice(2);
if (!file || !['enforce', 'report'].includes(mode)) {
  console.error('usage: node scripts/csp.mjs <index.html> <enforce|report>');
  process.exit(2);
}
const html = readFileSync(file, 'utf8');
const hashes = [];
for (const m of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi)) {
  const attrs = m[1] ?? '';
  if (/\ssrc\s*=/i.test(attrs) || !m[2].trim()) continue;
  hashes.push(`'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'`);
}
if (!hashes.length) {
  console.error(`csp: no inline script in ${file}; is it the built index.html?`);
  process.exit(1);
}

// The API and its socket are the same host on port 9098 (core/api/api.config.ts), so they follow the page's own host.
const api = '$scheme://$host:9098';
const policy = [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(' ')}`,
  // Angular puts component styles and [style] bindings inline; Google Fonts serves the font stylesheet.
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' data: https://fonts.gstatic.com",
  // Previews and downloads are blob: URLs; the stylesheet's icons are data: images; avatars come through the API.
  `img-src 'self' data: blob: ${api}`,
  `media-src 'self' blob: ${api}`,
  `connect-src 'self' ${api} ws://$host:9098 wss://$host:9098`,
  // pdf.js's worker is the console's own file.
  "worker-src 'self' blob:",
  // An HTML report is shown from a blob: URL in a frame with every sandbox permission off.
  "frame-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');

// Enforced: the policy goes before each location's own frame-ancestors. Report: only frame-ancestors is enforced (as
// X-Frame-Options already is) and the policy is reported.
process.stdout.write(`# Generated by scripts/csp.mjs from ${file.split('/').pop()} at build time (${mode}); do not edit.
set $csp "${policy}";
set $csp_enforced "${mode === 'enforce' ? '$csp; ' : ''}";
set $csp_report "${mode === 'report' ? '$csp' : ''}";
`);
