import { InspectResult, SchemaField, TemplateDefinition, TreeNode } from '../report-studio.model';

/**
 * The visual designer's model (MIG-404): the template's JSON -- its component tree -- and pure functions over it. The
 * designer edits only this tree, never HTML; every change is a new definition (the undo stack keeps the ones before),
 * which the server checks against the template schema and draws on the canvas.
 */

/** One component of the tree: its id, its type, its own settings and, for a container, its children. */
export interface Block {
  id: string;
  type: string;
  children?: Block[];
  [setting: string]: unknown;
}

/** Where a block sits: its list (the root's components or a container's children), its index and its parent. */
export interface Place { block: Block; list: Block[]; index: number; parent: Block | null; }

/** A page of the canvas: the body blocks between two page breaks, and the break that starts it. */
export interface CanvasPage { index: number; title: string; blockIds: string[]; breakId: string | null; }

/** A row of the Layers panel: a block at its depth in the tree. */
export interface LayerRow { id: string; type: string; label: string; depth: number; parentId: string | null; container: boolean; hidden: boolean; }

/** A palette entry from the server's registry (GET reportStudio.json/components). */
export interface PaletteEntry { type: string; group: string; label: string; description: string; defaults: Record<string, unknown>; }

/** The component types that hold others. A row holds columns only; header and footer are sections with a role. */
const CONTAINERS = new Set(['section', 'row', 'column', 'conditional', 'repeat']);

/** The words a person reads for a type, where the palette's label is not at hand. */
const TYPE_WORDS: Record<string, string> = {
  heading: 'Heading', text: 'Text', labelValue: 'Label and value', list: 'List', table: 'Table', image: 'Image or logo',
  section: 'Section', row: 'Row and columns', column: 'Column', divider: 'Divider', spacer: 'Spacer', pageBreak: 'Page break',
  pageNumber: 'Page number', dateTime: 'Generated at', reportId: 'Report id', templateVersion: 'Template version',
  sourceLabel: 'Data source', generatedBy: 'Generated by', confidentiality: 'Confidentiality',
  imageGrid: 'Image grid', signature: 'Signature', stamp: 'Stamp',
  // Report Studio phase 4.
  chart: 'Chart', metric: 'Metric', qrCode: 'QR code', conditional: 'Show only when', repeat: 'Repeat for each',
};

/** The icon (shared/ui/icon) a type is drawn with in the palette and the layers. */
const TYPE_ICONS: Record<string, string> = {
  heading: 'heading', text: 'text', labelValue: 'tag', list: 'list', table: 'table', image: 'image', section: 'layers', row: 'columns',
  column: 'columns', divider: 'minus', spacer: 'spacer', pageBreak: 'pageBreak', pageNumber: 'hash', dateTime: 'clock', reportId: 'hash',
  templateVersion: 'history', sourceLabel: 'database', generatedBy: 'user', confidentiality: 'shield',
  imageGrid: 'image', signature: 'edit', stamp: 'checkCircle',
  chart: 'chart', metric: 'trendingUp', qrCode: 'qr', conditional: 'filter', repeat: 'copy',
};

export function typeWord(type: string): string {
  return TYPE_WORDS[type] ?? type;
}

export function typeIcon(type: string): string {
  return TYPE_ICONS[type] ?? 'file';
}

export function isContainer(type: string): boolean {
  return CONTAINERS.has(type);
}

/** A section's role: header, footer or body. */
export function roleOf(b: Block): string {
  return b.type === 'section' ? String(b['role'] ?? 'body') : 'body';
}

/** What a person calls a block: its name, else its heading or text (shortened), else its type. */
export function blockLabel(b: Block): string {
  if (typeof b['name'] === 'string' && b['name'].trim()) return b['name'].trim();
  if (b.type === 'section' && roleOf(b) !== 'body') return roleOf(b) === 'header' ? 'Header' : 'Footer';
  for (const key of ['title', 'content', 'label', 'binding', 'dataset']) {
    const v = b[key];
    if (typeof v === 'string' && v.trim()) {
      const t = v.trim().replace(/\s+/g, ' ');
      return t.length > 42 ? `${t.slice(0, 40)}…` : t;
    }
  }
  return typeWord(b.type);
}

// ------------------------------------------------------------------ the tree

export function templateOf(def: TemplateDefinition): Record<string, unknown> & { components?: Block[] } {
  return def.template as Record<string, unknown> & { components?: Block[] };
}

export function componentsOf(def: TemplateDefinition): Block[] {
  const t = templateOf(def);
  if (!Array.isArray(t.components)) t.components = [];
  return t.components as Block[];
}

/** Every block, depth first, with its parent and depth. */
export function walk(blocks: Block[], visit: (b: Block, parent: Block | null, depth: number) => void, parent: Block | null = null,
                     depth = 0): void {
  for (const b of blocks) {
    visit(b, parent, depth);
    if (Array.isArray(b.children)) walk(b.children, visit, b, depth + 1);
  }
}

export function find(blocks: Block[], id: string, parent: Block | null = null): Place | null {
  for (let i = 0; i < blocks.length; i++) {
    const b = blocks[i];
    if (b.id === id) return { block: b, list: blocks, index: i, parent };
    if (Array.isArray(b.children)) {
      const inner = find(b.children, id, b);
      if (inner) return inner;
    }
  }
  return null;
}

/** True when `id` is `ancestor` itself or inside it. */
export function within(blocks: Block[], id: string, ancestor: string): boolean {
  const a = find(blocks, ancestor);
  if (!a) return false;
  if (a.block.id === id) return true;
  return !!(a.block.children && find(a.block.children, id));
}

export function allIds(blocks: Block[]): Set<string> {
  const ids = new Set<string>();
  walk(blocks, b => ids.add(b.id));
  return ids;
}

/** A new id for a type, unique in the tree (the schema's pattern: a letter, then letters, digits, - and _). */
export function newId(type: string, taken: Set<string>): string {
  const base = (type.replace(/[^A-Za-z0-9]/g, '') || 'block').replace(/^[^A-Za-z]+/, '') || 'block';
  let n = 1;
  while (taken.has(`${base}-${n}`)) n++;
  const id = `${base}-${n}`;
  taken.add(id);
  return id;
}

/** A copy of a block with new ids all the way down. */
export function cloneWithNewIds(b: Block, taken: Set<string>): Block {
  const copy = JSON.parse(JSON.stringify(b)) as Block;
  const renew = (x: Block) => {
    x.id = newId(x.type, taken);
    x.children?.forEach(renew);
  };
  renew(copy);
  return copy;
}

/** A new block from a palette entry: its defaults, a fresh id, and fresh ids for any children the defaults carry. */
export function fromPalette(entry: PaletteEntry, taken: Set<string>): Block {
  const block = { ...JSON.parse(JSON.stringify(entry.defaults)), type: entry.type } as Block;
  block.id = newId(entry.type, taken);
  block.children?.forEach(c => {
    const renew = (x: Block) => { x.id = newId(x.type, taken); x.children?.forEach(renew); };
    renew(c);
  });
  return block;
}

/**
 * Whether a container may hold a type (the schema's nesting rules): a row holds only columns, a column only a row's,
 * a header or footer only plain blocks, a body section neither header, footer nor page break. The root (null) holds
 * anything but a column.
 */
export function canHold(parent: Block | null, child: Block): boolean {
  if (!parent) return child.type !== 'column';
  if (parent.type === 'row') return child.type === 'column';
  if (child.type === 'column') return false;
  if (child.type === 'section' && roleOf(child) !== 'body') return false;
  if (child.type === 'pageBreak') return false;
  if (parent.type === 'section' && roleOf(parent) !== 'body' && isContainer(child.type) && child.type !== 'row') return false;
  return isContainer(parent.type);
}

/** Removes a block (and what it holds); true when it was there. */
export function removeBlock(blocks: Block[], id: string): boolean {
  const at = find(blocks, id);
  if (!at) return false;
  at.list.splice(at.index, 1);
  return true;
}

/** The list a parent id names: the root's components (null) or a container's children. */
export function listOf(blocks: Block[], parentId: string | null): Block[] | null {
  if (parentId === null) return blocks;
  const at = find(blocks, parentId);
  if (!at || !isContainer(at.block.type)) return null;
  if (!Array.isArray(at.block.children)) at.block.children = [];
  return at.block.children;
}

/** Puts a block into a parent at an index (clamped); false when the parent cannot hold it. */
export function insertBlock(blocks: Block[], parentId: string | null, index: number, block: Block): boolean {
  const parent = parentId === null ? null : find(blocks, parentId)?.block ?? null;
  if (parentId !== null && !parent) return false;
  if (!canHold(parent, block)) return false;
  const list = listOf(blocks, parentId);
  if (!list) return false;
  list.splice(Math.max(0, Math.min(index, list.length)), 0, block);
  return true;
}

/** Moves a block to a parent and index; never into itself. False when the move is not allowed. */
export function moveBlock(blocks: Block[], id: string, parentId: string | null, index: number): boolean {
  if (parentId !== null && within(blocks, parentId, id)) return false;
  const at = find(blocks, id);
  if (!at) return false;
  const parent = parentId === null ? null : find(blocks, parentId)?.block ?? null;
  if (!canHold(parent, at.block)) return false;
  const target = listOf(blocks, parentId);
  if (!target) return false;
  let i = index;
  if (target === at.list && at.index < index) i--;
  at.list.splice(at.index, 1);
  target.splice(Math.max(0, Math.min(i, target.length)), 0, at.block);
  return true;
}

/** The header and footer sections and the body blocks, as the compiler takes them (the first header and footer). */
export function parts(blocks: Block[]): { header: Block | null; footer: Block | null; body: Block[] } {
  let header: Block | null = null;
  let footer: Block | null = null;
  const body: Block[] = [];
  for (const b of blocks) {
    const role = roleOf(b);
    if (role === 'header' && !header) header = b;
    else if (role === 'footer' && !footer) footer = b;
    else body.push(b);
  }
  return { header, footer, body };
}

/** The body cut into pages at its top-level page breaks; each page named by its first heading. */
export function pagesOf(blocks: Block[]): CanvasPage[] {
  const { body } = parts(blocks);
  const pages: CanvasPage[] = [{ index: 0, title: '', blockIds: [], breakId: null }];
  for (const b of body) {
    if (b.type === 'pageBreak') {
      pages.push({ index: pages.length, title: '', blockIds: [], breakId: b.id });
    } else {
      pages[pages.length - 1].blockIds.push(b.id);
    }
  }
  for (const p of pages) {
    let title = '';
    walk(body.filter(b => p.blockIds.includes(b.id)), b => {
      if (!title && b.type === 'heading' && typeof b['content'] === 'string') title = b['content'] as string;
    });
    p.title = title.replace(/\{\{[^}]*\}\}/g, '…').trim() || `Page ${p.index + 1}`;
  }
  return pages;
}

/** The Layers panel's rows: every block in tree order, header first and footer last as the page has them. */
export function layerRows(blocks: Block[]): LayerRow[] {
  const rows: LayerRow[] = [];
  walk(blocks, (b, parent, depth) => rows.push({
    id: b.id, type: b.type, label: blockLabel(b), depth, parentId: parent?.id ?? null, container: isContainer(b.type), hidden: b['hidden'] === true,
  }));
  return rows;
}

// ------------------------------------------------------------------ bindings

const PLACEHOLDER = /\{\{\s*([^{}|]+?)\s*(?:\|[^}]*)?\}\}/g;

/** The primary dataset's id (the names a binding starts with): the contract's, else the first dataset's, else "primary". */
export function primaryDataset(def: TemplateDefinition): string {
  const t = templateOf(def) as { dataContract?: { primaryDataset?: string }; datasets?: { id?: string }[] };
  return t.dataContract?.primaryDataset || t.datasets?.[0]?.id || 'primary';
}

/** The names that read the primary dataset: its id, and its source alias when it starts at the root. */
export function primaryNames(def: TemplateDefinition): string[] {
  const id = primaryDataset(def);
  const t = templateOf(def) as { datasets?: { id?: string; sourceAlias?: string; rootPath?: string }[] };
  const out = [id];
  for (const d of t.datasets ?? []) {
    if (d.id === id && d.sourceAlias && (d.rootPath ?? '$') === '$') out.push(d.sourceAlias);
  }
  return out;
}

/** The primary dataset's root path (where its data starts in a source). */
export function rootPathOf(def: TemplateDefinition): string {
  const id = primaryDataset(def);
  const t = templateOf(def) as { datasets?: { id?: string; rootPath?: string }[] };
  return t.datasets?.find(d => d.id === id)?.rootPath ?? t.datasets?.[0]?.rootPath ?? '$';
}

/** A binding without its dataset name ("primary.summary.rate" is "summary.rate"); null when it reads another dataset. */
export function innerPath(binding: string, names: string[]): string | null {
  for (const n of names) {
    if (binding === n) return '';
    if (binding.startsWith(n + '.')) return binding.slice(n.length + 1);
  }
  return null;
}

/** Every data path one block reads: its binding, its table's rows and columns, and the placeholders in its text. */
export function pathsOf(b: Block): string[] {
  const out: string[] = [];
  for (const key of ['binding', 'dataset']) {
    if (typeof b[key] === 'string' && b[key]) out.push(b[key] as string);
  }
  for (const key of ['content', 'title', 'label']) {
    const text = b[key];
    if (typeof text !== 'string') continue;
    for (const m of text.matchAll(PLACEHOLDER)) {
      if (!m[1].trim().startsWith('report.')) out.push(m[1].trim());
    }
  }
  if (b.type === 'table' && typeof b['dataset'] === 'string' && Array.isArray(b['columns'])) {
    for (const c of b['columns'] as { field?: string }[]) {
      if (c.field) out.push(`${b['dataset']}[*].${c.field}`);
    }
  }
  return out;
}

/** The distinct data paths the whole template reads (the status bar's "N data fields used"). */
export function fieldsUsed(blocks: Block[]): number {
  const set = new Set<string>();
  walk(blocks, b => pathsOf(b).forEach(p => set.add(p)));
  return set.size;
}

/** A source's lists (paths whose type is a list, at the top of the data or inside objects -- never inside a list). */
export function collections(schema: SchemaField[]): SchemaField[] {
  return schema.filter(f => /list|array/i.test(f.type) && !f.path.includes('[]'));
}

/** The fields of one list's items ("by_department[].rate" is "rate" of "by_department"). */
export function itemFields(schema: SchemaField[], collection: string): SchemaField[] {
  const prefix = `${collection}[].`;
  return schema.filter(f => f.path.startsWith(prefix) && !f.path.slice(prefix.length).includes('[]'))
    .map(f => ({ ...f, path: f.path.slice(prefix.length) }));
}

/** A source's single values: paths outside any list that are not themselves objects or lists. */
export function scalars(schema: SchemaField[]): SchemaField[] {
  return schema.filter(f => !f.path.includes('[]') && !/object|list|array/i.test(f.type) && f.path !== '$');
}

/** A value of the sample at a schema path ("a.b", "list[].x" reads the first item); undefined when it is not there. */
export function valueAt(sample: unknown, path: string): unknown {
  let at: unknown = sample;
  for (const raw of path.split('.')) {
    const step = raw.replace(/\[\]$/, '');
    const each = raw.endsWith('[]');
    if (at === null || typeof at !== 'object') return undefined;
    at = (at as Record<string, unknown>)[step];
    if (each) {
      if (!Array.isArray(at)) return undefined;
      at = at[0];
    }
  }
  return at;
}

/** The first record of an inspect's sample (the data itself when it is one object). */
export function firstRecord(r: InspectResult | null): unknown {
  if (!r) return undefined;
  return Array.isArray(r.sample) ? r.sample[0] : r.sample;
}

/** How many items a list at a path has in the inspected data (the tree's count), or null. */
export function lengthAt(tree: TreeNode | undefined, path: string): number | null {
  if (!tree) return null;
  const want = path === '' ? '$' : `$.${path}`;
  let found: number | null = null;
  const visit = (n: TreeNode) => {
    if (found !== null) return;
    if (n.path === want && n.length != null) { found = n.length; return; }
    n.children?.forEach(visit);
  };
  visit(tree);
  return found;
}

/** A sample value as one short line. */
export function sampleText(v: unknown): string {
  if (v === undefined) return '';
  if (v === null) return 'empty';
  if (typeof v === 'object') return Array.isArray(v) ? `list of ${v.length}` : 'object';
  const t = String(v);
  return t.length > 60 ? `${t.slice(0, 58)}…` : t;
}

// ------------------------------------------------------------------ the page

/** A page's size in mm, as the template's page setup says (portrait unless landscape). */
export function pageSizeMm(def: TemplateDefinition): { width: number; height: number } {
  const page = (templateOf(def)['page'] ?? {}) as { size?: string; orientation?: string };
  const sizes: Record<string, [number, number]> = { A4: [210, 297], A3: [297, 420], A5: [148, 210], LETTER: [215.9, 279.4], LEGAL: [215.9, 355.6] };
  const [w, h] = sizes[page.size ?? 'A4'] ?? sizes['A4'];
  return page.orientation === 'landscape' ? { width: h, height: w } : { width: w, height: h };
}

/** CSS pixels in one millimetre (96 per inch). */
export const PX_PER_MM = 96 / 25.4;

/** The ruler's marks: every 10 mm, labelled every 50 (and the page's edge). */
export function rulerMarks(widthMm: number): { mm: number; label: string }[] {
  const out: { mm: number; label: string }[] = [];
  for (let mm = 0; mm <= widthMm; mm += 10) out.push({ mm, label: mm % 50 === 0 ? String(mm) : '' });
  const edge = Math.round(widthMm);
  // The page's edge is labelled; a 50 mm label too close to it is left out, so the two do not run together.
  for (const m of out) if (m.label && m.mm !== widthMm && edge - m.mm < 25) m.label = '';
  if (edge % 10 !== 0) out.push({ mm: widthMm, label: String(edge) });
  else if (out.length) out[out.length - 1].label = String(edge);
  return out;
}

/** A picture file's name, by its extension. */
const PICTURE_FILE = /\.(png|jpe?g|gif|webp)$/i;
/** A field named for a picture or its key, in generic words ("image", "photo", "scan", "image_key", "thumbnail_path"). */
const PICTURE_NAME = /(image|photo|picture|img|scan|thumb(nail)?)s?(_?(key|path|file|name|url))?$/i;

/** The first text value at a data path ("visits[].imageAfter") in the inspected sample rows, if any. */
export function firstTextAt(sample: unknown, path: string): string | null {
  const steps = path.split('.').filter(Boolean);
  const walk = (node: unknown, i: number): string | null => {
    if (Array.isArray(node)) {
      for (const item of node) { const v = walk(item, i); if (v != null) return v; }
      return null;
    }
    if (i === steps.length) return typeof node === 'string' ? node : null;
    if (node == null || typeof node !== 'object') return null;
    const key = steps[i].replace(/\[\]$/, '');
    return walk((node as Record<string, unknown>)[key], i + 1);
  };
  return walk(sample, 0);
}

/**
 * Whether a data field reads like a picture (the Data tab offers "show as image"): a text field whose name says so in
 * generic words, or whose sample value names a picture file. Nothing domain-specific: a wound report's imageAfter is
 * found by its values ("p-1042-after.jpg"), an outcomes file's image_key by its name.
 */
export function looksLikePicture(path: string, type: string, sample: unknown): boolean {
  if (!/string|text/i.test(type)) return false;
  const name = path.split(/[.[\]]/).filter(Boolean).pop() ?? '';
  if (PICTURE_NAME.test(name)) return true;
  const value = firstTextAt(sample, path);
  return value != null && PICTURE_FILE.test(value.trim());
}
